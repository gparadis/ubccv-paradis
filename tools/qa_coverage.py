    "number", "scheduled", "hours", "classsize", "class", "size", "taught",
    "per", "week", "term", "student", "program", "type", "year", "start",
    "finish", "supervisory", "role", "granting", "agency", "subject", "comp",
    "total", "principal", "investigator", "investigators", "co", "workshop",
