LIST_NUM_RE = re.compile(r"^\s*\d+\s*[.)]\s+")


def tokens(text: str) -> Counter:
    return Counter(
        t.lower() for t in TOKEN_RE.findall(text) if t.lower() not in IGNORE and len(t) > 1
    )


def source_tokens() -> Counter:
    total = Counter()
    for path in (
        "data/profile.yaml",
        "data/teaching.yaml",
        "data/research.yaml",
        "data/service.yaml",
        "data/awards.yaml",
        "data/other.yaml",
    ):
        with open(path, encoding="utf-8") as fh:
            total += tokens(yaml.safe_dump(yaml.safe_load(fh), allow_unicode=True))
    with open("data/publications.bib", encoding="utf-8") as fh:
        total += tokens(fh.read())
    return total


def docx_tokens() -> Counter:
    total = Counter()
    for b in load():
        if b["type"] == "p":
            # list numbering is regenerated at render time, not stored
            total += tokens(LIST_NUM_RE.sub("", b["text"]))
        else:
            for row in b["rows"]:
                for c in row:
                    total += tokens(c["text"])
    return total


# Differences that are correct by design: duplicated header blocks, boilerplate
# the template regenerates, a tokenizer artifact, one repaired typo, and one
# superseded submission date (FHOPS, accepted; see reference/EXTRACTION-NOTES.md).
EXPECTED = {
    "firstname": 2, "april": 1, "eric": 1, "vspsustainable": 1, "13": 1,
    "attendance": 1, "guest": 1, "internship": 1, "150": 1, "presenting": 1,
    "any": 1, "universities": 1, "acfarlane": 1, "06": 1,
}


def main() -> int:
    original, extracted = docx_tokens(), source_tokens()
    missing = Counter()
    for tok, n in original.items():
        gap = n - extracted.get(tok, 0) - EXPECTED.get(tok, 0)
        if gap > 0:
            missing[tok] = gap
    if not missing:
        print(
            f"coverage: OK -- every token in the docx is accounted for "
            f"({len(EXPECTED)} known exceptions, see reference/EXTRACTION-NOTES.md)"
        )
        return 0
    print(f"coverage: {len(missing)} unexpected token(s) missing from data/\n")
    for tok, n in missing.most_common(60):
        print(f"  {n:>3}x  {tok}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
