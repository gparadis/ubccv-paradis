#!/usr/bin/env python3
"""Check that the extracted sources still contain everything the docx had.

Compares the token multiset of every source paragraph/table cell against the
token multiset of data/*.yaml plus data/publications.bib. Any token that the
original has more often than the sources is reported as potential data loss.
This is formatting-agnostic, so it catches dropped authors, dates and amounts
without caring how they are laid out.
"""

