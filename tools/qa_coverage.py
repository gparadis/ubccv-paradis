    # headings and connective boilerplate regenerated by the templates
    "post", "secondary", "education", "employment", "prior", "coming",
    "granting", "tenure", "leaves", "absence", "teaching", "areas", "interest",
    "accomplishments", "courses", "ubc", "undergraduate", "graduate",
